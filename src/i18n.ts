export type Lang = "es" | "en";

/**
 * Diccionario de la interfaz.
 *
 * Una clave puede ser texto, una lista de variantes o una función. Las listas
 * existen para el narrador de la carrera: `t()` sortea una variante en cada
 * llamada, así el relator no repite la misma frase tres veces en treinta
 * segundos. `setLang` ignora las listas al pintar los atributos `data-i`, de
 * modo que una clave con variantes no puede usarse en el markup.
 */

export interface Dict {
  [key: string]: string | string[] | ((...args: never[]) => string);
  cLead: (n: string) => string;
  cWin: (n: string) => string;
  summary: (w: string, n: number, d: string, r: number, u: string) => string;
  drawIn: (mmss: string) => string;
  drandTry: (i: number, n: number) => string;
  drawTry: (i: number, n: number) => string;
  cConstPass: (n: string) => string;
  cLanes: (k: number, n: number) => string;
  cWheelSplit: (segs: number, rep: number) => string;
  cWheelOn: (n: string) => string;
  cPasOut: (n: string) => string;
  csvRows: (n: number) => string;
  tellBody: (w: string, prize: string, n: number, u: string) => string;
}

/**
 * Elige una variante de una clave con varias.
 *
 * Usa el azar sembrado con la ronda de drand cuando hay un juego corriendo, y
 * `Math.random()` fuera de un juego. Así dos corridas de la misma ronda narran
 * exactamente igual, que es la misma promesa que hace el resto del producto.
 */
let pickRng: (() => number) | null = null;
const pick = (xs: string[]): string => xs[Math.floor((pickRng ?? Math.random)() * xs.length)] ?? "";

/** El juego en curso presta su azar sembrado. `null` al terminar. */
export function setPickSeed(rng: (() => number) | null): void {
  pickRng = rng;
}

